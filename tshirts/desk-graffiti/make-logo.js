// Writes raising-hell.js: the official Raising Hell mark as an SVG string with a hand-drawn
// treatment (wobbly edges and a touch of ink bleed), for desk.html to draw in thick black marker.
// Run: node tshirts/desk-graffiti/make-logo.js
const fs = require('fs');
const path = require('path');
const { logos, renderLogo } = require('../../logos/final/logos');

const mark = logos.find(l => l.id === 'raising-hell');
const INK = '#17120f';
let svg = renderLogo(mark, { color: INK, size: 1000, title: false });

// Wobble the edges like a marker line drawn by hand, then soften very slightly for ink bleed.
const filter = `<filter id="hand" x="-5%" y="-5%" width="110%" height="110%">
  <feTurbulence type="fractalNoise" baseFrequency="0.045" numOctaves="2" seed="11" result="n"/>
  <feDisplacementMap in="SourceGraphic" in2="n" scale="3.2" xChannelSelector="R" yChannelSelector="G" result="d"/>
  <feGaussianBlur in="d" stdDeviation="0.35"/>
</filter>`;
const rect = svg.match(/<rect width="200" height="200" fill="[^"]+" mask="url\(#[^)]+\)"\/>/);
if (!rect) throw new Error('mark rect not found');
svg = svg.replace(rect[0], `${filter}<g filter="url(#hand)">${rect[0]}</g>`);

fs.writeFileSync(path.join(__dirname, 'raising-hell.js'),
  `// Generated by make-logo.js. Do not edit by hand.\nwindow.LOGO_SVG = ${JSON.stringify(svg)};\n`);
console.log('Wrote raising-hell.js');
