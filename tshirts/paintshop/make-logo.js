// Builds crisp, multi-color versions of an official Coma Toast mark for the PaintShop tee.
// Outline style: each part (e.g. toast and halo) is drawn as colored line work only, so the dark
// shirt fills the mark. Writes logos.js (for splash.html) and svg/<mark>-<colorway>.svg.
// Run: node tshirts/paintshop/make-logo.js
const fs = require('fs');
const path = require('path');
const { logos } = require('../../logos/final/logos');

const MARK = process.env.MARK || 'plain';
const mark = logos.find(l => l.id === MARK);
// Visible area of each mark inside its 200-unit square (center and size), used to place it on the shirt.
const BOX = {
  plain: { cx: 100, cy: 131.4, w: 104.7, h: 103.4 },
  saint: { cx: 100, cy: 120.6, w: 115.4, h: 124.8 },
  'raising-hell': { cx: 100, cy: 116, w: 176, h: 134 },
};

// Colors per part, in the mark's part order. Plain: [toast]. Saint: [toast, halo]. Raising Hell:
// [wings, horns, toast]. Each colorway also has a primary and an accent color, which drive the paint
// palette and the back wordmark so every shirt matches its logo.
const COLORWAYS = {
  plain: {
    'hot-wire': { name: 'Hot Wire', parts: ['#ff2e88'], accent: '#c6ff00', desc: 'pink toast, lime accents' },
    'toxic': { name: 'Toxic', parts: ['#ffe600'], accent: '#00e5ff', desc: 'yellow toast, cyan accents' },
    'riot': { name: 'Riot', parts: ['#00e5ff'], accent: '#ff2e88', desc: 'cyan toast, pink accents' },
  },
  saint: {
    'hot-wire': { name: 'Hot Wire', parts: ['#ff2e88', '#c6ff00'], desc: 'pink toast, lime halo' },
    'toxic': { name: 'Toxic', parts: ['#ffe600', '#00e5ff'], desc: 'yellow toast, cyan halo' },
    'riot': { name: 'Riot', parts: ['#00e5ff', '#ff2e88'], desc: 'cyan toast, pink halo' },
  },
  'raising-hell': {
    'hot-wire': { name: 'Hot Wire', parts: ['#c6ff00', '#c6ff00', '#ff2e88'], desc: 'pink toast, lime wings' },
    'toxic': { name: 'Toxic', parts: ['#00e5ff', '#00e5ff', '#ffe600'], desc: 'yellow toast, cyan wings' },
    'riot': { name: 'Riot', parts: ['#ff2e88', '#ff2e88', '#00e5ff'], desc: 'cyan toast, pink wings' },
  },
}[MARK];

// Inverse (outline) style: the dark shirt fills the mark and the color is only the line work.
// Each part's silhouette becomes a colored band of width EDGE drawn just inside its edge (so the
// outline and the gap between halo and crust match the official mark), and the face, which is cut
// out of the solid mark, is drawn in the same color instead.
const EDGE = 4.6; // page units (the face lines are about 3.5)
const scaleOf = shape => +((shape.match(/scale\(([\d.]+)\)/) || [])[1] || 1);
function render(colors, id, size) {
  const body = mark.parts.map((p, i) => {
    const c = colors[i], sw = (2 * EDGE / scaleOf(p.shape)).toFixed(2);
    return `<mask id="${id}-c${i}" maskUnits="userSpaceOnUse" x="0" y="0" width="200" height="200"><g fill="#fff">${p.shape}</g></mask>
<g mask="url(#${id}-c${i})" fill="none" stroke="${c}" stroke-width="${sw}" stroke-linejoin="round">${p.shape}</g>
${(p.detail || '').replace(/stroke="#000"/g, `stroke="${c}"`)}`;
  }).join('\n');
  const dims = size ? ` width="${size}" height="${size}"` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200"${dims}>\n${body}\n</svg>`;
}

fs.mkdirSync(path.join(__dirname, 'svg'), { recursive: true });
const js = {};
for (const [key, cw] of Object.entries(COLORWAYS)) {
  const svg = render(cw.parts, `${MARK}-${key}`, 1000);
  fs.writeFileSync(path.join(__dirname, 'svg', `${MARK}-${key}.svg`), svg + '\n');
  js[key] = { name: cw.name, desc: cw.desc, colors: cw.parts, primary: cw.parts[0], accent: cw.accent || cw.parts[1], svg };
}
fs.writeFileSync(path.join(__dirname, 'logos.js'), `// Generated by make-logo.js (mark: ${MARK}). Do not edit by hand.\nwindow.LOGO_MARK = ${JSON.stringify(MARK)};\nwindow.LOGO_BOX = ${JSON.stringify(BOX[MARK])};\nwindow.LOGOS = ${JSON.stringify(js)};\n`);
console.log('Wrote', Object.keys(js).length, 'colorways');
